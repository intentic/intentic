import { mkdir, writeFile } from "node:fs/promises";

// Generates public/ext-shims/*.js — the static ESM shims that re-export the host's module instances from
// globalThis.__intenticHost (published by src/extension-host/hostModules.ts). The import map in index.html
// points extension bundles' bare `vue` / `@intentic/extension-api` specifiers at these files, so a bundle
// shares the app's one vue instance. Committed output; re-run when either package's export surface changes:
//   node scripts/generate-ext-shims.mjs
const targets = [
    { specifier: "vue", file: "vue.js" },
    { specifier: "@intentic/extension-api", file: "extension-api.js" },
];

await mkdir(new URL("../public/ext-shims/", import.meta.url), { recursive: true });
for (const { specifier, file } of targets) {
    const module = await import(specifier);
    const names = Object.keys(module)
        .filter((name) => name !== "default" && /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name))
        .toSorted();
    const lines = [
        `// Generated by scripts/generate-ext-shims.mjs — do not edit.`,
        `// Re-exports the host's "${specifier}" instance (src/extension-host/hostModules.ts).`,
        `const m = globalThis.__intenticHost.modules[${JSON.stringify(specifier)}];`,
        ...names.map((name) => `export const ${name} = m[${JSON.stringify(name)}];`),
        ...("default" in module ? [`export default m["default"];`] : []),
        ``,
    ];
    await writeFile(new URL(`../public/ext-shims/${file}`, import.meta.url), lines.join("\n"));
    console.log(`ext-shims/${file}: ${names.length} exports`);
}
