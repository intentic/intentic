// Writes generated resource files, or with `--check` only compares them: the one shape both generators share, so each
// fails the same way, naming the command that brings the files back in step.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative } from "node:path";

/** `files` maps an absolute path to its whole text. Returns the exit code. */
export const emit = (files, { check, command, root }) => {
    const stale = [...files].filter(([path, text]) => !existsSync(path) || readFileSync(path, `utf8`) !== text);
    if (check) {
        for (const [path] of stale) {
            console.error(`${relative(root, path)} is stale: run ${command}`);
        }
        return stale.length === 0 ? 0 : 1;
    }
    for (const [path, text] of stale) {
        mkdirSync(dirname(path), { recursive: true });
        writeFileSync(path, text);
        console.log(`wrote ${relative(root, path)}`);
    }
    return 0;
};

/** The comment every generated file opens with. */
export const banner = (script, source) =>
    `<!-- GENERATED by _editor/android-app/scripts/${script} from ${source}: do not edit. Run \`node _editor/android-app/scripts/${script}\`. -->`;
