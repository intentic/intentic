import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { argv } from "node:process";
import { pathToFileURL } from "node:url";
import { packageRoot } from "@intentic/constants/node";
import { extensionUiNames } from "../../../_editor/extension-ui/names.mjs";

// Generates public/ext-shims/*.js — the static ESM shims that re-export the host's module instances from
// globalThis.__intenticHost (published by src/extension-host/hostModules.ts). The import map in index.html
// points extension bundles' bare specifiers at these files, so a bundle shares the app's one instance of each.
// Export names come from importing the package in node — except @intentic/extension-ui, whose runtime is a
// .vue component graph node can't load: its names ride names.mjs (hostModules asserts the list in dev).
// Committed output; re-run when any package's export surface changes:
//   node scripts/generate-ext-shims.mjs
//
// The generation is a pure function so the committed files can be CHECKED rather than trusted
// (extShims.test.ts). A shim that drifts from its package fails silently and late: the bundle imports a name
// the shim never declares, the host hands back `undefined`, and the extension dies at render with no clue
// pointing here. That is exactly what a `cmp` → `ui` rename did — the source moved, the committed shim did
// not, and nothing said so until a screen went blank.
const targets = [
    { specifier: "vue", file: "vue.js" },
    { specifier: "@intentic/extension-api", file: "extension-api.js" },
    { specifier: "@intentic/extension-manifest", file: "extension-manifest.js" },
    { specifier: "@intentic/extension-ui", file: "extension-ui.js", names: extensionUiNames },
    { specifier: "@tanstack/vue-query", file: "vue-query.js" },
];

const isIdentifier = (name) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name);

/** Where the committed shims live. */
export const shimsDir = join(packageRoot(import.meta.url), "public/ext-shims");

/** Every shim this repo should contain, as `{ file, content }` — what the script writes and the test asserts. */
export const extShims = async () =>
    Promise.all(
        targets.map(async (target) => {
            const module = target.names === undefined ? await import(target.specifier) : undefined;
            const names = (target.names ?? Object.keys(module)).filter((name) => name !== "default" && isIdentifier(name)).toSorted();
            const lines = [
                `// Generated by scripts/generate-ext-shims.mjs — do not edit.`,
                `// Re-exports the host's "${target.specifier}" instance (src/extension-host/hostModules.ts).`,
                `const m = globalThis.__intenticHost.modules[${JSON.stringify(target.specifier)}];`,
                ...names.map((name) => `export const ${name} = m[${JSON.stringify(name)}];`),
                ...(module !== undefined && "default" in module ? [`export default m["default"];`] : []),
                ``,
            ];
            return { file: target.file, content: lines.join("\n"), exports: names.length };
        }),
    );

if (argv[1] !== undefined && import.meta.url === pathToFileURL(argv[1]).href) {
    await mkdir(shimsDir, { recursive: true });
    for (const shim of await extShims()) {
        await writeFile(join(shimsDir, shim.file), shim.content);
        console.log(`ext-shims/${shim.file}: ${shim.exports} exports`);
    }
}
