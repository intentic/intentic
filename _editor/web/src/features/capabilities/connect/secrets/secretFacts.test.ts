// The sentences an open secret says about itself: when it was last spent and on what, said in words with any command it
// went into held apart as code, and where it lives, a path told apart from a place named in words.
import { timeAgo } from "@intentic/ui/format";
import { capitalized, lastUseWords, storedWords } from "./secretFacts";

const NOW = Date.UTC(2026, 9, 26, 12, 0, 0);
const HOUR = 3_600_000;
// How long ago, in the app's own words for it, so the sentence is pinned and the clock's spelling is not.
const ago = (hours: number): string => capitalized(timeAgo(NOW - hours * HOUR, { now: NOW, days: true }));

it("says a command's use in words, with the command itself held apart as code", () => {
    expect(lastUseWords({ at: NOW - 7 * HOUR, lane: `shell`, detail: `cd /tmp && git push` }, NOW)).toEqual({
        said: `${ago(7)} · in a command`,
        code: `cd /tmp && git push`,
        note: undefined,
    });
});

it("names where a gateway request went inside the sentence, and who released a gated use under it", () => {
    expect(lastUseWords({ at: NOW - 2 * HOUR, lane: `gateway`, detail: `api.github.com`, approvedBy: `ada@acme.dev` }, NOW)).toEqual({
        said: `${ago(2)} · sent through the gateway to api.github.com`,
        code: undefined,
        note: `Released by ada@acme.dev`,
    });
});

it("says a use typed on a computer with no detail as typed into a window", () => {
    expect(lastUseWords({ at: NOW - 2 * HOUR, lane: `device` }, NOW).said).toBe(`${ago(2)} · typed into a window`);
});

it("tells a path from a place named in words, and says when the sandbox made the value", () => {
    expect(storedWords({ storedAt: `.intentic/secrets/auth/sandbox-secrets.json`, kind: `env` })).toEqual({
        said: `.intentic/secrets/auth/sandbox-secrets.json`,
        path: true,
        note: undefined,
    });
    expect(storedWords({ storedAt: `the capability vault`, kind: `capability` }).path).toBe(false);
    expect(storedWords({ storedAt: `generated by the sandbox`, kind: `generated` }).note).toBe(`Generated for you`);
});

it("opens a value with a capital, leaving the rest as said", () => {
    expect(capitalized(`asks each time`)).toBe(`Asks each time`);
    expect(capitalized(``)).toBe(``);
});
