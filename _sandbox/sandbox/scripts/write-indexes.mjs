// Writes the daemon's generated indexes from its source text (src/store/shapes/state-modules.ts sourceDefinitions):
// src/bootstrap/state-registry.ts, every stored document and structural boot step, src/app-raw-routes.ts, every raw
// route table, and src/bootstrap/slices/slice-registry.ts, every leaf slice of the composition. `--check` writes nothing and exits 1 naming each index that is stale. Plain `node`, with the scan
// module's types stripped by node itself, so it runs before any install of tsx and loads no daemon module.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { sourceDefinitions } from "../src/store/shapes/state-modules.ts";

const PACKAGE = dirname(import.meta.dirname);
const SOURCE = join(PACKAGE, "src");

// One import per module, each naming what it exports in name order, modules in path order.
const importsOf = (definitions, from) => {
    const names = new Map();
    for (const { module, name } of definitions) {
        names.set(module, [...(names.get(module) ?? []), name]);
    }
    return [...names]
        .toSorted(([a], [b]) => a.localeCompare(b))
        .map(([module, exported]) => `import { ${exported.toSorted().join(", ")} } from "${from(module.replace(/\.ts$/, ".js"))}";`);
};

// The registry module's source: an import of every definition by the name its module exports it under, and two lists
// read when called, so a module that reaches the registry back through an import cycle never meets an unfilled binding.
const registrySource = ({ documents, steps }) =>
    [
        "// Generated by scripts/write-indexes.mjs from every `export const name = defineDocument(…)` and `defineStep(…)` in",
        "// src/. Do not edit; run `node scripts/write-indexes.mjs` in _sandbox/sandbox. The one list of every stored document and",
        "// structural boot step this build knows: main.ts hands it to the boot step and state-plan.ts plans with it, so the two",
        "// agree whatever else either process loads. state-registry.test.ts fails when a definition is missing from it. Above",
        "// every subsystem, in the boot wiring, on purpose: nothing under a subsystem imports bootstrap/.",
        'import type { DocumentSpec } from "../store/evolution/documents.js";',
        'import type { StructuralStep } from "../store/evolution/state-steps.js";',
        ...importsOf([...documents, ...steps], (path) => (path.startsWith("bootstrap/") ? `./${path.slice("bootstrap/".length)}` : `../${path}`)),
        "",
        "export const stateDocuments = (): readonly DocumentSpec[] => [",
        ...documents.map(({ name }) => `    ${name},`),
        "];",
        "",
        "// By id, not by the order modules happened to load in: the plan must not depend on an import graph.",
        "export const stateSteps = (): readonly StructuralStep[] =>",
        "    [",
        ...steps.map(({ name }) => `        ${name},`),
        "    ].toSorted((a, b) => a.id.localeCompare(b.id));",
        "",
    ].join("\n");

// Every raw route table merged into one, which must serve every route the daemon serves: a declared route no table
// serves fails the `satisfies` at compile time, and a route two tables serve throws when the app is built.
const rawRoutesSource = ({ rawRoutes }) =>
    [
        "// Generated by scripts/write-indexes.mjs from every `export const name = defineRawRoutes(…)` in src/. Do not edit; run",
        "// `node scripts/write-indexes.mjs` in _sandbox/sandbox. Every raw route the daemon serves, one table per wiring unit:",
        "// app.ts registers them in RAW_ROUTES order, and a declared route no table serves fails to compile here. A root file,",
        "// since it imports route modules from every subsystem.",
        'import type { DaemonRawRouteKey } from "@intentic/sandbox-contract/protocol/raw/raw-routes";',
        'import type { Services } from "./composition.js";',
        'import { mergeRawRoutes, type RawRouteTable } from "./http/raw-route-server.js";',
        ...importsOf(rawRoutes, (path) => `./${path}`),
        "",
        "export const appRawRoutes = (services: Services) =>",
        "    mergeRawRoutes(",
        ...rawRoutes.map(({ name }) => `        ${name}(services),`),
        "    ) satisfies RawRouteTable<DaemonRawRouteKey>;",
        "",
    ].join("\n");

// Every leaf slice, built from the one core composition.ts hands over and torn down with it. Its own directory, since
// bootstrap/ and src/ each hold as many files as the layout allows.
const slicesSource = ({ slices }) => {
    const byModule = new Map();
    for (const { module, name, members } of slices) {
        byModule.set(module, [...(byModule.get(module) ?? []), name, `type ${members}`]);
    }
    const unique = (names) => [...new Set(names)].toSorted((a, b) => a.replace(/^type /, "").localeCompare(b.replace(/^type /, "")));
    return [
        "// Generated by scripts/write-indexes.mjs from every `export const name = defineSlice<Members>(…)` in src/. Do not edit;",
        "// run `node scripts/write-indexes.mjs` in _sandbox/sandbox. Every leaf slice of the composition: each builds from the",
        "// hand-ordered core alone, so their order is not significant, and Services carries every member they build.",
        'import type { CompositionCore, Services } from "../../composition.js";',
        'import { distinctMembers, type SliceStopped, stopsOf } from "../../seams/slice.js";',
        ...[...byModule]
            .toSorted(([a], [b]) => a.localeCompare(b))
            .map(([module, names]) => `import { ${unique(names).join(", ")} } from "../../${module.replace(/\.ts$/, ".js")}";`),
        "",
        // One member type per line, as the formatter lays an intersection out.
        ...(slices.length === 0
            ? ["export type LeafMembers = Record<never, never>;"]
            : slices.map(({ members }, at) =>
                  at === 0
                      ? `export type LeafMembers = ${members}${slices.length === 1 ? ";" : " &"}`
                      : `    ${members}${at === slices.length - 1 ? ";" : " &"}`,
              )),
        "",
        "// Each slice built once over the core; a member two of them build, or one the core already holds, throws.",
        "export const buildLeafSlices = (core: CompositionCore): LeafMembers => {",
        "    const built = {",
        ...slices.map(({ name }) => `        ${name}: ${name}.build(core),`),
        "    };",
        "    distinctMembers(",
        "        Object.entries(built).map(([slice, members]) => [slice, Object.keys(members)] as const),",
        "        Object.keys(core),",
        "    );",
        "    return {",
        ...slices.map(({ name }) => `        ...built.${name},`),
        "    };",
        "};",
        "",
        "// What each slice started and how it stops, in slice path order: no two of them depend on each other.",
        "export const leafTeardown = (services: Services): readonly (() => SliceStopped)[] => [",
        ...slices.map(({ name }) => `    ...stopsOf(${name}, services),`),
        "];",
        "",
    ].join("\n");
};

const INDEXES = [
    { path: "src/bootstrap/state-registry.ts", source: registrySource },
    { path: "src/app-raw-routes.ts", source: rawRoutesSource },
    { path: "src/bootstrap/slices/slice-registry.ts", source: slicesSource },
];

const check = process.argv.includes("--check");
const definitions = await sourceDefinitions(SOURCE).catch((error) => {
    process.stderr.write(`daemon indexes: ${error instanceof Error ? error.message : String(error)}\n`);
    process.exit(1);
});
const stale = [];
for (const index of INDEXES) {
    const want = index.source(definitions);
    const file = join(PACKAGE, index.path);
    // allow(silent-catch): an index not written yet is one that differs from what it should be
    const have = await readFile(file, "utf8").catch(() => undefined);
    if (have === want) {
        continue;
    }
    stale.push(index.path);
    if (!check) {
        await mkdir(dirname(file), { recursive: true });
        await writeFile(file, want);
    }
}
const counts = `${definitions.documents.length} documents, ${definitions.steps.length} steps, ${definitions.rawRoutes.length} raw route tables, ${definitions.slices.length} leaf slices`;
if (check && stale.length > 0) {
    process.stderr.write(`daemon indexes: stale in _sandbox/sandbox: ${stale.join(", ")}; run \`node scripts/write-indexes.mjs\` there\n`);
    process.exit(1);
}
process.stdout.write(`daemon indexes: ${check || stale.length === 0 ? "current" : `wrote ${stale.join(", ")}`} (${counts})\n`);
