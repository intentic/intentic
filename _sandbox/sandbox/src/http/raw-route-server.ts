import { type DaemonRawRouteKey, RAW_ROUTE_LIST, type RawRouteKey, rawRoutePath } from "@intentic/sandbox-contract/protocol/raw/raw-routes";
import type { Handler, Hono } from "hono";
import type { AppEnv } from "../app-env.js";

// The one way a raw (non-oRPC) route is added to the app: under its declaration in RAW_ROUTES, which carries its
// policy, so the daemon serves no route without one. A `{param}` is spelled Hono's way, `:param`, on the way in.
export const rawRouteServer =
    (app: Hono<AppEnv>) =>
    (key: RawRouteKey, handler: Handler<AppEnv>): void => {
        app.on(key.slice(0, key.indexOf(" ")), rawRoutePath(key).replace(/\{([^}]+)\}/gu, ":$1"), handler);
    };

// A wiring unit's raw routes: one handler for each declared key it serves.
export type RawRouteTable<K extends DaemonRawRouteKey = DaemonRawRouteKey> = { readonly [P in K]: Handler<AppEnv> };

// A unit's table, built once per app from what it needs; src/app-raw-routes.ts (generated by scripts/write-indexes.mjs)
// finds each by `export const name = defineRawRoutes(…)` at a module's top level.
export const defineRawRoutes = <Deps, K extends DaemonRawRouteKey>(build: (deps: Deps) => RawRouteTable<K>): ((deps: Deps) => RawRouteTable<K>) => build;

// The keys of every table in a union of them.
type KeysOf<T> = T extends unknown ? keyof T & DaemonRawRouteKey : never;

// What merging `Tables` answers: one table serving every key any of them serves.
export type MergedRawRoutes<Tables extends readonly Partial<RawRouteTable>[]> = RawRouteTable<KeysOf<Tables[number]>>;

// The tables as one; a key two tables serve throws, since only one of them could ever answer it.
export const mergeRawRoutes = <const Tables extends readonly Partial<RawRouteTable>[]>(...tables: Tables): MergedRawRoutes<Tables> => {
    const merged = new Map<string, Handler<AppEnv>>();
    for (const table of tables) {
        for (const [key, handler] of Object.entries(table)) {
            if (merged.has(key)) {
                throw new Error(`raw route ${key} is served by two tables`);
            }
            if (handler !== undefined) {
                merged.set(key, handler);
            }
        }
    }
    // SAFETY: every key of every table was copied above, so the record holds exactly their union.
    return Object.fromEntries(merged) as MergedRawRoutes<Tables>;
};

// Registers a table's routes on `app` in RAW_ROUTES order, which alone decides which of two overlapping routes answers.
// A route netd serves itself (RouteMeta `netd`) never reaches the daemon, so none is registered for it.
export const serveRawRoutes = (app: Hono<AppEnv>, table: Partial<Readonly<Record<RawRouteKey, Handler<AppEnv>>>>): Hono<AppEnv> => {
    const serve = rawRouteServer(app);
    for (const route of RAW_ROUTE_LIST) {
        const handler = route.meta.netd === true ? undefined : table[route.name];
        if (handler !== undefined) {
            serve(route.name, handler);
        }
    }
    return app;
};
