// The Pi extension the daemon hands every Pi turn (`-e`, pi-rpc.ts), as the text Pi loads. Kept apart from the code
// that writes it because this is source another process runs, not code this one does: plain JavaScript, valid as the
// TypeScript Pi's loader expects, importing only Node's own modules, so it loads on whichever Pi the owner installed
// without reaching for Pi's packages (renamed across releases) or `typebox` (the tool's parameters are a plain JSON
// schema, which Pi validates as such).
//
// It does four things:
// - registers `ask_user`, a tool that asks the person through Pi's own dialogs (`ctx.ui.select` with choices,
//   `ctx.ui.input` without), which pi-extension-ui.ts parks on the question card every runtime shares;
// - mounts the turn's remote MCP servers through `pi.registerMcpServer`, session-scoped, on a Pi with built-in MCP
//   (0.99 and later; pi-rpc.ts hands them over only then), each declared to the model (`exposure: "direct"`) as the
//   other runtimes declare them. Older Pi has no such method, and the servers are skipped;
// - puts every tool call to the turn's hook socket before it runs (`tool_call`), and does what the daemon answers:
//   refuse it, run it with its input changed (a shell line through the terminal panel, its secrets resolved), or run it
//   as it is. A call it cannot ask about is refused, which is also what Pi does with a handler that throws. MCP calls,
//   codemode's included, pass the same handler (Pi's mcp.md). Being loaded first (`-e` before discovery), it sees every
//   call before any other extension does;
// - puts every tool result to the same socket after it runs (`tool_result`), and hands Pi the result the daemon
//   answers: secrets masked, outside content sealed, the owner's per-edit checks said. A result it cannot ask about is
//   withheld.
// It also declines trust in the project (`project_trust`), which Pi's RPC mode already does unless a saved decision or
// the owner's settings say otherwise: an extension the agent wrote into the workspace would otherwise load into a later
// turn's Pi after this one and could change a call the rules had already allowed. Once its handlers are in place it
// says so on the socket (`/ready`), and the daemon starts no prompt on a Pi that never did.
// The servers, bearers included, and the socket's path come from a per-turn file the daemon names in PI_TURN_ENV; the
// extension reads it once and removes it, so the bearers sit on disk only until Pi has loaded them.

// Names the per-turn file to the extension.
export const PI_TURN_ENV = "INTENTIC_PI_TURN";

// What the per-turn file holds.
export interface PiTurnFile {
    readonly mcp: readonly { readonly name: string; readonly url: string; readonly token?: string; readonly timeoutMs?: number }[];
    // The turn's hook socket (pi-hooks.ts); absent, every call is refused, since none can be asked about.
    readonly hooks?: string;
}

// The tool's name, as the model calls it.
export const PI_ASK_TOOL = "ask_user";

export const PI_EXTENSION_SOURCE = [
    `// managed by intentic: written for every Pi turn the daemon starts (src/runtimes/pi/pi-extension.ts).`,
    `import { readFileSync, rmSync } from "node:fs";`,
    `import { request } from "node:http";`,
    ``,
    `const readTurn = () => {`,
    `    const file = process.env.${PI_TURN_ENV};`,
    `    if (!file) {`,
    `        return { mcp: [] };`,
    `    }`,
    `    try {`,
    `        return JSON.parse(readFileSync(file, "utf8"));`,
    `    } catch {`,
    `        return { mcp: [] };`,
    `    } finally {`,
    `        rmSync(file, { force: true });`,
    `    }`,
    `};`,
    ``,
    `// Read once per process: a reload of the extension finds the file gone and keeps what was read.`,
    `const turn = (globalThis.__intenticPiTurn ??= readTurn());`,
    ``,
    `// Pi passes the context last in some releases and before the signal in others; it is the argument with a ui.`,
    `const contextOf = (args) => args.find((arg) => arg !== null && typeof arg === "object" && arg.ui && typeof arg.ui.select === "function");`,
    ``,
    `const said = (text, answer) => ({ content: [{ type: "text", text }], details: { answer } });`,
    ``,
    `// Pi's own MCP names: letters, digits, dash, underscore and dot.`,
    `const serverName = (name) => String(name).replace(/[^A-Za-z0-9_.-]/g, "_");`,
    ``,
    `// One question to the daemon over the turn's socket, answered with a JSON object. No deadline: a call the owner's`,
    `// rules hold waits on a person. Pi's own signal ends the wait, and an ended wait is a refusal.`,
    `const ask = (path, body, signal) =>`,
    `    new Promise((resolve, reject) => {`,
    `        if (!turn.hooks) {`,
    `            reject(new Error("this Pi was started without the sandbox's hook socket"));`,
    `            return;`,
    `        }`,
    `        const sent = request({ socketPath: turn.hooks, path, method: "POST", headers: { "content-type": "application/json" } }, (response) => {`,
    `            const chunks = [];`,
    `            response.on("data", (chunk) => chunks.push(chunk));`,
    `            response.on("error", reject);`,
    `            response.on("end", () => {`,
    `                try {`,
    `                    const answer = JSON.parse(Buffer.concat(chunks).toString("utf8"));`,
    `                    if (answer === null || typeof answer !== "object") {`,
    `                        throw new Error("the sandbox answered something other than an object");`,
    `                    }`,
    `                    resolve(answer);`,
    `                } catch (error) {`,
    `                    reject(error);`,
    `                }`,
    `            });`,
    `        });`,
    `        sent.on("error", reject);`,
    `        if (signal) {`,
    `            if (signal.aborted) {`,
    `                sent.destroy(new Error("the call was stopped"));`,
    `            } else {`,
    `                signal.addEventListener("abort", () => sent.destroy(new Error("the call was stopped")), { once: true });`,
    `            }`,
    `        }`,
    `        sent.end(JSON.stringify(body));`,
    `    });`,
    ``,
    `const reasonOf = (error) => String(error && error.message ? error.message : error);`,
    ``,
    `const UNCHECKED = (error) =>`,
    `    "The sandbox could not check this call against your owner's rules (" + reasonOf(error) + "), so it did not run. " +`,
    `    "Do not retry it: carry on with what you can do without it, and say plainly what you left undone.";`,
    `const WITHHELD = (error) =>`,
    `    "[intentic withheld this tool's output: the sandbox could not check it for secrets (" + reasonOf(error) + ").]";`,
    ``,
    `// What the rules had to say about a call they let run (where an install writes), said with its result.`,
    `const notes = new Map();`,
    ``,
    `const guard = (pi) => {`,
    `    pi.on("project_trust", () => ({ trusted: "no" }));`,
    `    pi.on("tool_call", async (event, ctx) => {`,
    `        let answer;`,
    `        try {`,
    `            answer = await ask("/tool-call", { tool: event.toolName, id: event.toolCallId, input: event.input, cwd: ctx && ctx.cwd }, ctx && ctx.signal);`,
    `        } catch (error) {`,
    `            return { block: true, reason: UNCHECKED(error) };`,
    `        }`,
    `        if (answer.block) {`,
    `            return { block: true, reason: String(answer.reason || "Your owner's rules refused this call.") };`,
    `        }`,
    `        if (answer.input && typeof answer.input === "object") {`,
    `            // In place: Pi runs the object its handlers were given.`,
    `            for (const key of Object.keys(event.input)) {`,
    `                if (!(key in answer.input)) {`,
    `                    delete event.input[key];`,
    `                }`,
    `            }`,
    `            Object.assign(event.input, answer.input);`,
    `        }`,
    `        if (typeof answer.context === "string" && answer.context !== "") {`,
    `            notes.set(event.toolCallId, answer.context);`,
    `        }`,
    `        return undefined;`,
    `    });`,
    `    pi.on("tool_result", async (event, ctx) => {`,
    `        const note = notes.get(event.toolCallId);`,
    `        notes.delete(event.toolCallId);`,
    `        let content;`,
    `        try {`,
    `            const answer = await ask(`,
    `                "/tool-result",`,
    `                { tool: event.toolName, input: event.input, content: event.content, isError: event.isError === true, cwd: ctx && ctx.cwd },`,
    `                ctx && ctx.signal,`,
    `            );`,
    `            content = Array.isArray(answer.content) ? answer.content : event.content;`,
    `        } catch (error) {`,
    `            return { content: [{ type: "text", text: WITHHELD(error) }] };`,
    `        }`,
    `        if (note) {`,
    `            content = [...content, { type: "text", text: note }];`,
    `        }`,
    `        return content === event.content ? undefined : { content };`,
    `    });`,
    `};`,
    ``,
    `export default function intentic(pi) {`,
    `    // First, so no tool runs on a Pi whose calls nobody checks; said to the daemon only once it is in place.`,
    `    if (typeof pi.on === "function") {`,
    `        guard(pi);`,
    `        ask("/ready", {}).catch(`,
    `            // allow(silent-catch): a Pi that cannot say it is ready gets no prompt from the daemon, which is the answer`,
    `            () => {},`,
    `        );`,
    `    }`,
    `    pi.registerTool({`,
    `        name: "${PI_ASK_TOOL}",`,
    `        label: "Ask the user",`,
    `        description:`,
    `            "Ask the person you are working for a question and wait for their answer. Give options when there are a few clear " +`,
    `            "choices; they can always answer in their own words instead. Ask only what is genuinely theirs to decide.",`,
    `        promptSnippet: "Ask the person a question and wait for their answer",`,
    `        promptGuidelines: [`,
    `            "Use ${PI_ASK_TOOL} when a decision is genuinely the person's to make and the request, the code and sensible defaults cannot settle it.",`,
    `        ],`,
    `        parameters: {`,
    `            type: "object",`,
    `            properties: {`,
    `                question: { type: "string", description: "The question, as a full sentence." },`,
    `                options: { type: "array", items: { type: "string" }, description: "Choices to offer, a few words each. Leave out for a free-text answer." },`,
    `            },`,
    `            required: ["question"],`,
    `        },`,
    `        async execute(...args) {`,
    `            const params = args[1] ?? {};`,
    `            const ctx = contextOf(args);`,
    `            if (!ctx) {`,
    `                return said("No one can be asked from here. Carry on with what you can, and say what you assumed.", null);`,
    `            }`,
    `            const question = String(params.question ?? "").trim();`,
    `            const options = Array.isArray(params.options) ? params.options.map(String).filter((option) => option.trim() !== "") : [];`,
    `            const answer = options.length > 0 ? await ctx.ui.select(question, options) : await ctx.ui.input(question);`,
    `            if (answer === undefined || answer === null || String(answer).trim() === "") {`,
    `                return said("The person dismissed the question without answering. Carry on with what you can, and say what you assumed.", null);`,
    `            }`,
    `            return said("The person answered: " + String(answer), String(answer));`,
    `        },`,
    `    });`,
    `    if (typeof pi.registerMcpServer !== "function") {`,
    `        return;`,
    `    }`,
    `    for (const server of turn.mcp ?? []) {`,
    `        pi.registerMcpServer(serverName(server.name), {`,
    `            url: server.url,`,
    `            exposure: "direct",`,
    `            ...(server.token ? { headers: { Authorization: "Bearer " + server.token } } : {}),`,
    `            ...(server.timeoutMs ? { timeout: Math.ceil(server.timeoutMs / 1000) } : {}),`,
    `        });`,
    `    }`,
    `}`,
    ``,
].join("\n");
