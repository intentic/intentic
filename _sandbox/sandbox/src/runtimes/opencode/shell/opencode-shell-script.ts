// The script OpenCode runs as its shell (opencode-shell.ts): text another process runs, kept apart from the daemon code
// that answers it. Named `bash` on disk, so OpenCode describes the shell to its model as bash and scans its commands as
// bash; it runs every command in /bin/bash itself. CommonJS, since a file named `bash` has no extension to make node read
// it as a module; plain JavaScript with no template literals, so nothing in it reads as this file's interpolation.

// The file name OpenCode is told to run.
export const SHELL_SCRIPT_NAME = "bash";

export const shellScript = (socketPath: string, node: string): string =>
    [
        `#!${node}`,
        `// managed by intentic: overwritten whenever the daemon starts OpenCode (src/runtimes/opencode/shell/opencode-shell-script.ts).`,
        `// OpenCode's shell. Asks the daemon how to run each command (in the conversation's terminal pane, with its secret`,
        `// references resolved), and hands what the command prints back to the daemon to mask before OpenCode reads it.`,
        `"use strict";`,
        `const { request } = require("node:http");`,
        `const { spawn } = require("node:child_process");`,
        `const { StringDecoder } = require("node:string_decoder");`,
        ``,
        `const SOCKET = ${JSON.stringify(socketPath)};`,
        `const BASH = "/bin/bash";`,
        `const NOT_RUN = "Not run: the sandbox daemon could not be reached to prepare this command. Do not retry it in a loop.\\n";`,
        `const WITHHELD = "\\n[The rest of this command's output was withheld: the sandbox daemon could not be reached to mask it.]\\n";`,
        `// Whole lines are masked as they come; a line longer than this is cut at a space at least TAIL from its end, since a`,
        `// stored value is one word and no word straddles a cut there.`,
        `const LONG_LINE = 65536;`,
        `const TAIL = 4096;`,
        ``,
        `const ask = (path, body) =>`,
        `    new Promise((settle, fail) => {`,
        `        const call = request({ socketPath: SOCKET, path, method: "POST", headers: { "content-type": "application/json" } }, (response) => {`,
        `            const parts = [];`,
        `            response.on("data", (part) => parts.push(part));`,
        `            response.on("error", fail);`,
        `            response.on("end", () => {`,
        `                try {`,
        `                    settle(JSON.parse(Buffer.concat(parts).toString("utf8")));`,
        `                } catch (error) {`,
        `                    fail(error);`,
        `                }`,
        `            });`,
        `        });`,
        `        call.on("error", fail);`,
        `        call.end(JSON.stringify(body));`,
        `    });`,
        ``,
        `// Runs an argv with this process's own output, exiting as it exits.`,
        `const plain = (argv) => {`,
        `    const child = spawn(argv[0], argv.slice(1), { stdio: "inherit" });`,
        `    child.on("error", (error) => {`,
        `        process.stderr.write("failed to start " + argv[0] + ": " + error.message + "\\n");`,
        `        process.exit(127);`,
        `    });`,
        `    child.on("exit", (code, signal) => process.exit(code === null ? (signal === null ? 1 : 128) : code));`,
        `};`,
        ``,
        `const cutOf = (text) => {`,
        `    const limit = text.length - TAIL;`,
        `    for (let at = limit - 1; at > 0 && at >= limit - 16384; at -= 1) {`,
        `        if (text[at] === " " || text[at] === "\\t") {`,
        `            return at + 1;`,
        `        }`,
        `    }`,
        `    return limit;`,
        `};`,
        ``,
        `// Runs an argv with what it prints (stdout and stderr, in arrival order) masked by the daemon before it is written,`,
        `// by the run the daemon prepared it as.`,
        `const masked = (session, run, argv) => {`,
        `    const child = spawn(argv[0], argv.slice(1), { stdio: ["ignore", "pipe", "pipe"] });`,
        `    const decoder = new StringDecoder("utf8");`,
        `    let held = "";`,
        `    let withheld = false;`,
        `    let chain = Promise.resolve();`,
        `    let timer;`,
        `    const send = (text) => {`,
        `        chain = chain.then(async () => {`,
        `            if (withheld || text === "") {`,
        `                return;`,
        `            }`,
        `            try {`,
        `                const reply = await ask("/output", { session, run, output: text });`,
        `                if (typeof reply.output !== "string") {`,
        `                    throw new Error(typeof reply.withheld === "string" ? reply.withheld : "no output");`,
        `                }`,
        `                process.stdout.write(reply.output);`,
        `            } catch (error) {`,
        `                withheld = true;`,
        `                process.stdout.write(WITHHELD);`,
        `            }`,
        `        });`,
        `    };`,
        `    const flush = (all) => {`,
        `        clearTimeout(timer);`,
        `        timer = undefined;`,
        `        const line = held.lastIndexOf("\\n") + 1;`,
        `        const cut = all ? held.length : line > 0 || held.length < LONG_LINE ? line : cutOf(held);`,
        `        if (cut > 0) {`,
        `            send(held.slice(0, cut));`,
        `            held = held.slice(cut);`,
        `        }`,
        `    };`,
        `    const take = (chunk) => {`,
        `        held += decoder.write(chunk);`,
        `        if (held.length >= LONG_LINE) {`,
        `            flush(false);`,
        `        } else if (timer === undefined) {`,
        `            timer = setTimeout(() => flush(false), 200);`,
        `        }`,
        `    };`,
        `    child.stdout.on("data", take);`,
        `    child.stderr.on("data", take);`,
        `    child.on("error", (error) => {`,
        `        held += "failed to start " + argv[0] + ": " + error.message + "\\n";`,
        `    });`,
        `    child.on("close", (code, signal) => {`,
        `        held += decoder.end();`,
        `        flush(true);`,
        `        void chain`,
        `            .then(() => ask("/done", { run }))`,
        // allow(silent-catch): a `/done` that did not land leaves the daemon holding the run's route until it expires
        // (RUN_HELD_MS); the command's own exit code must still reach OpenCode.
        `            .catch(() => undefined)`,
        `            .then(() => process.exit(code === null ? (signal === null ? 127 : 128) : code));`,
        `    });`,
        `};`,
        ``,
        `const main = async () => {`,
        `    const args = process.argv.slice(2);`,
        `    while (args[0] === "-l" || args[0] === "--login") {`,
        `        args.shift();`,
        `    }`,
        `    const session = process.env.OPENCODE_SESSION_ID;`,
        `    // Anything but one command, or a command no session asked for, is bash's as it came.`,
        `    if (args[0] !== "-c" || typeof args[1] !== "string" || typeof session !== "string" || session === "") {`,
        `        plain([BASH, ...args]);`,
        `        return;`,
        `    }`,
        `    let plan;`,
        `    try {`,
        `        plan = await ask("/prepare", { session, command: args[1], cwd: process.cwd() });`,
        `    } catch {`,
        `        plan = undefined;`,
        `    }`,
        `    if (typeof plan?.refused === "string") {`,
        `        process.stdout.write(plan.refused + "\\n");`,
        `        process.exit(1);`,
        `    }`,
        `    if (!Array.isArray(plan?.argv) || plan.argv.length === 0 || !plan.argv.every((part) => typeof part === "string")) {`,
        `        process.stdout.write(NOT_RUN);`,
        `        process.exit(1);`,
        `    }`,
        `    if (plan.masked === true && typeof plan.run === "string") {`,
        `        masked(session, plan.run, plan.argv);`,
        `    } else if (plan.masked === true) {`,
        `        process.stdout.write(NOT_RUN);`,
        `        process.exit(1);`,
        `    } else {`,
        `        plain(plan.argv);`,
        `    }`,
        `};`,
        `void main();`,
        ``,
    ].join("\n");
