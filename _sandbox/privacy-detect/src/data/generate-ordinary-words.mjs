#!/usr/bin/env node
// Rebuilds ordinary-words.ts: the ordinary English words the name lists know nothing about, neither as a first name nor
// as a surname. common-words.ts and ambiguous.ts hold the words that are names too; this holds the rest, so that a
// capitalized "Crew", "Haven" or "Listings" is not taken for a surname nobody listed. Only fullNameAlone
// (standalone.ts) reads it: a pair of words the local name model tags as a person, or the vault would match alone,
// needs one word that is neither an ordinary word nor a name that is one, and a product called "<first name> Crew" has
// none.
//
// Source: the Leipzig Corpora Collection (https://wortschatz.uni-leipzig.de/en/download), its English news corpus of
// 300,000 sentences, licensed CC BY (© Universität Leipzig / Sächsische Akademie der Wissenschaften / InfAI). Only the
// word list (`<corpus>-words.txt`: id, word, count) is read. Download
// https://downloads.wortschatz-leipzig.de/corpora/eng_news_2023_300K.tar.gz, unpack it, then:
//
//   node --import tsx src/data/generate-ordinary-words.mjs <the unpacked directory>
//
// The thresholds are generate-common-words.mjs's: written in lowercase at least MIN_LOWERCASE times, and at least
// LOWERCASE_SHARE as often as capitalized. A surname nobody listed is written lowercase only by mistake, so it stays out
// ("Lovelace", "Okafor"), while a word that is mostly a word is in. English only: the Polish corpus run the same way
// changed no find the vault held, and would have more than doubled the file.

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { wordInfo } from "../lexicon.js";

const MIN_LOWERCASE = 20;
const LOWERCASE_SHARE = 0.2;
const MIN_LENGTH = 3;

const source = process.argv[2];
if (source === undefined) {
    console.error("usage: node --import tsx generate-ordinary-words.mjs <directory with the unpacked eng_news corpus>");
    process.exit(1);
}

const wordFiles = (dir) =>
    readdirSync(dir).flatMap((entry) => {
        const path = join(dir, entry);
        return statSync(path).isDirectory() ? wordFiles(path) : entry.endsWith("-words.txt") ? [path] : [];
    });

const files = wordFiles(source).filter((file) => basename(file).startsWith("eng_"));
const [file] = files;
if (file === undefined || files.length > 1) {
    console.error(`expected one English word list under ${source}, found ${files.length}`);
    process.exit(1);
}
const corpus = basename(file).replace(/-words\.txt$/u, "");

const LOWER = /^\p{Ll}+$/u;
const CAPITALIZED = /^\p{Lu}\p{Ll}+$/u;
const lower = new Map();
const capitalized = new Map();
for (const line of readFileSync(file, "utf8").split("\n")) {
    const [, word, count] = line.split("\t");
    if (word === undefined || count === undefined) {
        continue;
    }
    const normal = word.normalize("NFC");
    if (LOWER.test(normal)) {
        lower.set(normal, (lower.get(normal) ?? 0) + Number(count));
    } else if (CAPITALIZED.test(normal)) {
        const key = normal.toLowerCase();
        capitalized.set(key, (capitalized.get(key) ?? 0) + Number(count));
    }
}

const words = [];
for (const [word, count] of lower) {
    if (word.length < MIN_LENGTH || count < MIN_LOWERCASE || count < LOWERCASE_SHARE * (capitalized.get(word) ?? 0)) {
        continue;
    }
    const info = wordInfo(word);
    // A name, or a word the other lists already settle, is theirs to say.
    if (!(info.first || info.surname || info.surnameForm || info.ambiguous || info.never)) {
        words.push(word);
    }
}
words.sort();

const header = [
    "// Ordinary English words the name lists know nothing about, lowercase, one per line: each is written in lowercase in",
    "// the corpus below often enough to be a word there.",
    "// Source: Leipzig Corpora Collection, https://wortschatz.uni-leipzig.de/en/download, CC BY",
    `// (© Universität Leipzig / Sächsische Akademie der Wissenschaften / InfAI). Word list of the corpus ${corpus}.`,
    `// Thresholds: written lowercase at least ${MIN_LOWERCASE} times, and at least ${LOWERCASE_SHARE} times as often as capitalized.`,
    "// Generated by generate-ordinary-words.mjs from the source named there; do not edit by hand.",
].join("\n");
const body = `export const ORDINARY_WORDS_EN =\n    ${JSON.stringify(words.join("\n"))};\n`;
writeFileSync(join(import.meta.dirname, "ordinary-words.ts"), `${header}\n\n${body}`);
console.log(`ordinary-words.ts: ${words.length} words from ${corpus}`);
